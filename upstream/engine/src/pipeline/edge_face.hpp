// 一个字符在某个字面里的字形；没有这个字返回 nullptr。
inline const GlyphInfo* glyph(int face, char ch) {
    if (face < 0 || face >= kFaceCount) return nullptr;
    const int code = int(static_cast<unsigned char>(ch)) - kAsciiFirst;
    if (code < 0 || code >= kAsciiCount) return nullptr;
    const int slot = kAscii[code];
    if (slot < 0) return nullptr;
    return &kGlyphs[kFaceFirst[face] + slot];
}

